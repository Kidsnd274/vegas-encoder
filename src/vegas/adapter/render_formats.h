inline LONG RenderFormatCount() {
#if defined(VEGAS_ENCODER_B6_RECIPE_PROOF)
  // Both one-format policies take precedence over a retained fallback flag.
  if (Cfg().encode && Cfg().legacyContainers && !Cfg().legacyManualNames && !Cfg().legacyAutoNames)
    return static_cast<LONG>(std::size(kLegacyFormats));
#endif
  return 1;
}
inline const RenderFormat& RenderFormatAt(LONG index) {
  return RenderFormatCount() == 1 ? kModernFormat : kLegacyFormats[index];
}
inline const RenderFormat* FindRenderFormat(const GUID& filter) {
  for (LONG index = 0; index < RenderFormatCount(); ++index)
    if (RenderFormatAt(index).filter == filter) return &RenderFormatAt(index);
  return nullptr;
}
