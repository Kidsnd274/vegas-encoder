"""Generate app built-ins and fixed VEGAS starters from one product catalog.

Only packaging: normalization/compile/validation remain in the C++ core.
VEGAS entry order and GUIDs are persistent identities; append new entries.
"""
import argparse
import json
from pathlib import Path
from uuid import UUID

root = Path(__file__).resolve().parent.parent.parent
args = argparse.ArgumentParser()
args.add_argument('--check', action='store_true')
options = args.parse_args()
source = json.loads((root / 'schema/builtin-presets.v1.json').read_text(encoding='utf-8'))
assert source['builtins'] == 1
presets = source['presets']
by_id = {p['recipe']['id']: p for p in presets}
assert len(by_id) == len(presets), 'Duplicate built-in ID.'
assert all(p['builtin'] and p['revision'] >= 1 for p in presets)
guids = [UUID(p['guid']) for p in source['vegas']]
assert len(set(guids)) == len(guids), 'Duplicate VEGAS GUID.'
assert len({p['presetId'] for p in source['vegas']}) == len(source['vegas'])
assert [p['index'] for p in source['vegas']] == list(range(2, len(guids) + 2)), 'Preserve VEGAS slot order; append new entries.'
content = '''// Generated by scripts/etc/Generate-ServiceBuiltins.py. Product-policy recipes
// from schema/builtin-presets.v1.json; native core derives facts.
import 'dart:convert';
import 'package:ve_core/ve_core.dart';
import 'models.dart';

List<Preset> builtinPresets() =>
    jsonMaps(jsonDecode(_json)).map(Preset.fromJson).toList(growable: false);
const _json =
    r\'''%s\''';
''' % json.dumps(presets, ensure_ascii=False, separators=(',', ':'))
native = ['// Generated by scripts/etc/Generate-ServiceBuiltins.py from schema/builtin-presets.v1.json.',
          '// Included after the preserved id-0 probe and id-1 general settings template.',
          '// Array order and GUIDs are stable VEGAS template identities.']
for entry, guid in zip(source['vegas'], guids):
    preset = by_id[entry['presetId']]
    payload = json.dumps(preset, ensure_ascii=True, separators=(',', ':'))
    assert ')VE_PRESET"' not in payload
    fields = guid.fields
    tail = guid.bytes[8:]
    initializer = ('{0x%08x, 0x%04x, 0x%04x, {%s}}' %
                   (fields[0], fields[1], fields[2], ', '.join('0x%02x' % n for n in tail)))
    name = 'L' + json.dumps(entry['name'], ensure_ascii=True)
    notes = 'L' + json.dumps(entry['notes'], ensure_ascii=True)
    native.append('    {%s, MAKEFOURCC(\'P\', \'0\', \'1\', \'0\'), %s, %s, R"VE_PRESET(%s)VE_PRESET"},' %
                  (initializer, name, notes, payload))
native.append('')
for target, text in [(root / 'packages/ve_services/lib/src/builtin_presets.dart', content),
                     (root / 'src/vegas/adapter/builtin_presets.generated.inc', '\n'.join(native))]:
    if options.check:
        if target.read_text(encoding='utf-8') != text:
            raise SystemExit(f'Stale built-ins: {target}; run scripts/etc/Generate-ServiceBuiltins.py.')
    else:
        target.write_text(text, encoding='utf-8', newline='\n')
print(f'Built-ins consistent: {len(presets)} app recipes, {len(guids)} VEGAS starters; no runtime claims.')
