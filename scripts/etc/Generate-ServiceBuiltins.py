"""Package the six accepted recipe snapshots; no compiler/probe facts are inferred."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent.parent
args = argparse.ArgumentParser()
args.add_argument('--check', action='store_true')
options = args.parse_args()
source = json.loads((root / 'schema/fixtures/b0/core-and-services.json').read_text(encoding='utf-8'))
presets = []
for fixture in source['fixtures']:
    preset = fixture['preset']
    if preset['recipe']['id'] == 'yt-hevc-nv':
        preset['recipe']['notes'] = '10-bit HEVC on NVIDIA hardware. Test this encoder on this PC before using it.'
        preset['recipe']['tags'] = ['YouTube', 'NVIDIA']
    presets.append({**preset, 'revision': 1, 'favorite': False, 'pinned': False,
                    'updatedAt': '2026-10-14T00:00:00Z', 'origin': None,
                    'requires': {'encoders': [], 'minFFmpegVersion': None, 'known': False}})
content = '''// Generated by scripts/etc/Generate-ServiceBuiltins.py. Product-policy recipes
// adopted from the six original design snapshots; native core derives facts.
import 'dart:convert';
import 'package:ve_core/ve_core.dart';
import 'models.dart';

List<Preset> builtinPresets() =>
    jsonMaps(jsonDecode(_json)).map(Preset.fromJson).toList(growable: false);
const _json =
    r\'''%s\''';
''' % json.dumps(presets, ensure_ascii=False, separators=(',', ':'))
target = root / 'packages/ve_services/lib/src/builtin_presets.dart'
if options.check:
    if target.read_text(encoding='utf-8') != content:
        raise SystemExit('Stale packaged service built-ins.')
else:
    target.write_text(content, encoding='utf-8', newline='\n')
print('Service built-ins consistent: six recipe snapshots; no FFmpeg runtime claims.')
