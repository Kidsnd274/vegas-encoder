"""Record/check the six existing recipes' real-core argv for B1, not FakeVeCore.

No edited-state sweep, host or FFmpeg execution. Run after Generate-CoreData.py and
build-core.cmd. Embedded test data supports the standalone Dart AOT test route.
"""
import argparse
import json
from pathlib import Path
import sys
from importlib import import_module

sys.path.insert(0,str(Path(__file__).resolve().parent))
module = import_module('Test-CoreFFmpegProfiles')
ROOT = module.ROOT
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check',action='store_true')
parser.add_argument('--core',type=Path,default=ROOT/'build/release/vegas-encoder/core/ve_core.dll')
args = parser.parse_args()
core = module.Core(args.core.resolve(strict=True))
bundle = json.loads((ROOT/'schema/fixtures/b0/core-and-services.json').read_text(encoding='utf-8'))
fixtures = bundle['fixtures'] + bundle['additionalFixtures']
argv = {}
ordered = []
for index,fixture in enumerate(fixtures):
    result = core.call('ve_compile',{key:fixture[key] for key in ['recipe','media','paths']})
    assert not any(i['level'] == 'error' for i in result['issues']),result['issues']
    ordered.append(result['argv'])
    if index < len(bundle['fixtures']):
        argv[fixture['recipe']['id']] = result['argv']
goldens = dict(goldens=1,provenance='B1 real C++ core: six original recipes plus existing popup context; Windows-tested flag mappings; no VEGAS qualification.',argv=argv,additionalArgv=ordered[len(bundle['fixtures']):])
json_text = json.dumps(goldens,ensure_ascii=False,indent=2)+'\n'
dart_text = '// Generated by scripts/etc/Generate-CoreGoldens.py; six recipes plus existing popup context.\nconst b1CoreArgv = <List<String>> '+json.dumps(ordered,ensure_ascii=True,indent=2).replace('$','\\$')+';\n'
for path,text in [(ROOT/'schema/fixtures/b1/core-argv.json',json_text),(ROOT/'packages/ve_core/test/b1_argv.dart',dart_text)]:
    if args.check:
        assert path.read_text(encoding='utf-8') == text,f'Stale {path}; regenerate after reviewing intended command changes.'
    else:
        path.parent.mkdir(parents=True,exist_ok=True)
        path.write_text(text,encoding='utf-8')
print('B1 argv goldens checked (six recipes plus existing popup).' if args.check else 'B1 argv goldens generated (six recipes plus existing popup); B0 FakeVeCore fixtures unchanged.')
