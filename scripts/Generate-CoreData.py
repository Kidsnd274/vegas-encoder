"""Embed committed schema/profile data for the portable core; no network or probes."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
parser.add_argument('--bootstrap', action='store_true', help='One-time B0 design-data extraction, not Windows qualification')
args = parser.parse_args()
if args.bootstrap:
    bundle = json.loads((ROOT/'schema/fixtures/b0/core-and-services.json').read_text(encoding='utf-8'))
    profiles = bundle['profiles']
    profiles['provenance'] = 'B2 bootstrap from B0 design data; Linux FFmpeg 8.1.3; NOT Windows-qualified (B1 pending)'
    preferred = {'aac':('fltp',32),'libfdk_aac':('s16',16),'libopus':('flt',32),
                 'libvorbis':('fltp',32),'libmp3lame':('fltp',32),'ac3':('fltp',32),
                 'eac3':('fltp',32),'flac':('s32',24),'alac':('s32p',24),'pcm_s16le':('s16',16),
                 'pcm_s24le':('s32',24),'pcm_f32le':('flt',32)}
    for profile in profiles['audio']:
        profile['sampleFormat'], profile['sampleBits'] = preferred[profile['id']]
    for name, value in [('encoder-profiles.v1.json', profiles),
                        ('encoder-options.design.v1.json', {'provenance':profiles['provenance'], 'encoders':bundle['details']})]:
        (ROOT/'schema'/name).write_text(json.dumps(value, ensure_ascii=False, indent=2)+'\n',encoding='utf-8')

inputs = [('RecipeSchema','recipe.v1.schema.json'),('Profiles','encoder-profiles.v1.json'),
          ('Options','encoder-options.design.v1.json')]
lines = ['// Generated by scripts/Generate-CoreData.py. B1 Windows recapture pending.',
         '#pragma once', '#include <string>', 'namespace ve::data {']
for symbol, name in inputs:
    value = json.loads((ROOT/'schema'/name).read_text(encoding='utf-8'))
    text = json.dumps(value,ensure_ascii=True,separators=(',',':'))
    # Each separate literal stays below MSVC's literal-size limit.
    chunks = [text[i:i+12000] for i in range(0,len(text),12000)]
    lines.append(f'inline std::string {symbol}() {{')
    lines.append('  std::string text;')
    for chunk in chunks:
        assert ')VE_DATA"' not in chunk
        lines.append('  text += R"VE_DATA('+chunk+')VE_DATA";')
    lines += ['  return text;', '}']
lines += ['} // namespace ve::data', '']
dest = ROOT/'src/core/profiles/data.h'
text = '\n'.join(lines)
if args.check:
    if dest.read_text(encoding='utf-8').replace('\r\n','\n') != text:
        raise SystemExit('Stale core data; run python -I scripts/Generate-CoreData.py')
else:
    dest.parent.mkdir(parents=True,exist_ok=True)
    dest.write_text(text,encoding='utf-8')
print('Core data checked.' if args.check else 'Core data embedded (design provenance; not Windows qualification).')
