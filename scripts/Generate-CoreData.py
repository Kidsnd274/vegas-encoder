"""Embed committed schema/profile data for the portable core; no network or probes."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()

inputs = [('RecipeSchema','recipe.v1.schema.json'),('Profiles','encoder-profiles.v1.json'),
          ('Options','encoder-options.windows.v1.json')]
lines = ['// Generated by scripts/Generate-CoreData.py from committed schema and B1 Windows data.',
         '#pragma once', '#include <string>', 'namespace ve::data {']
for symbol, name in inputs:
    value = json.loads((ROOT/'schema'/name).read_text(encoding='utf-8'))
    text = json.dumps(value,ensure_ascii=True,separators=(',',':'))
    # Each separate literal stays below MSVC's literal-size limit.
    chunks = [text[i:i+12000] for i in range(0,len(text),12000)]
    lines.append(f'inline std::string {symbol}() {{')
    lines.append('  std::string text;')
    for chunk in chunks:
        assert ')VE_DATA"' not in chunk
        lines.append('  text += R"VE_DATA('+chunk+')VE_DATA";')
    lines += ['  return text;', '}']
lines += ['} // namespace ve::data', '']
dest = ROOT/'src/core/profiles/data.h'
text = '\n'.join(lines)
if args.check:
    if dest.read_text(encoding='utf-8').replace('\r\n','\n') != text:
        raise SystemExit('Stale core data; run python -I scripts/Generate-CoreData.py')
else:
    dest.parent.mkdir(parents=True,exist_ok=True)
    dest.write_text(text,encoding='utf-8')
print('Core data checked.' if args.check else 'Core data embedded (B1 Windows facts; no VEGAS qualification).')
