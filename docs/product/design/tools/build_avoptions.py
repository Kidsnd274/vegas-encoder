"""Build mockup option data from captured `ffmpeg -h encoder=X` text.

Design-review tooling only. This is a throwaway prototype of the capability
parser described in docs/product/FFMPEG_INTEGRATION.md; the product parser will
live in the Flutter app and be tested against captured fixtures.

Usage: python -I build_avoptions.py <probe-dir> <out.js>
The probe directory holds enc_<name>.txt files captured from FFmpeg.
"""

import json
import pathlib
import re
import sys

HEADER = re.compile(r"^Encoder (\S+) \[(.*)\]:$")
CAP = re.compile(r"^\s{4}(General capabilities|Threading capabilities|Supported hardware devices|"
                 r"Supported pixel formats|Supported sample rates|Supported sample formats|"
                 r"Supported channel layouts):\s*(.*)$")
OPTION = re.compile(r"^  -(\S+)\s+<(\w+)>\s+([E.][D.][F.][V.][A.][S.][X.][R.][B.][T.][P.])\s?(.*)$")
# Constant names can overflow their column ("autovariance-biased 3"), leaving a
# single space before the value; the value is absent for some constants.
CONST = re.compile(r"^     (\S+)\s+(?:(\S+)\s+)?([E.][D.][F.][V.][A.][S.][X.][R.][B.][T.][P.])\s?(.*)$")
RANGE = re.compile(r"\(from (\S+) to (\S+)\)")
DEFAULT = re.compile(r"\(default (.*)\)\s*$")


def parse(text):
    enc = {"options": []}
    current = None
    for line in text.splitlines():
        if not line.strip() or line.startswith("Exiting with exit code"):
            continue
        if m := HEADER.match(line):
            enc["name"], enc["long"] = m.group(1), m.group(2)
        elif m := CAP.match(line):
            key = {"General capabilities": "caps", "Threading capabilities": "threading",
                   "Supported hardware devices": "hwdevices", "Supported pixel formats": "pixfmts",
                   "Supported sample rates": "samplerates", "Supported sample formats": "samplefmts",
                   "Supported channel layouts": "layouts"}[m.group(1)]
            enc[key] = m.group(2).split()
        elif m := OPTION.match(line):
            if dup := next((o for o in enc["options"] if o["name"] == m.group(1)), None):
                current = dup  # dnxhd prints -profile twice; constants follow the repeat
                continue
            desc = m.group(4).strip()
            opt = {"name": m.group(1), "type": m.group(2), "flags": m.group(3)}
            if d := DEFAULT.search(desc):
                opt["default"] = d.group(1).strip('"')
                desc = desc[:d.start()].strip()
            if r := RANGE.search(desc):
                opt["min"], opt["max"] = r.group(1), r.group(2)
                desc = (desc[:r.start()] + desc[r.end():]).strip()
            opt["desc"] = desc
            enc["options"].append(opt)
            current = opt
        elif current and (m := CONST.match(line)):
            current.setdefault("consts", []).append(
                {"name": m.group(1), "value": m.group(2) or "", "desc": m.group(4).strip()})
        elif line.rstrip().endswith("AVOptions:"):
            current = None
    return enc


def main():
    src, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    data = {}
    for path in sorted(src.glob("enc_*.txt")):
        enc = parse(path.read_text(errors="replace"))
        if enc.get("name"):
            data[enc["name"]] = enc
    version = (src / "version.txt").read_text().splitlines()[0] if (src / "version.txt").exists() else ""
    body = json.dumps({"source": version, "encoders": data}, indent=1)
    out.write_text("// Generated by tools/build_avoptions.py from captured FFmpeg help text.\n"
                   "// Real option data for design mockups; not a product capability cache.\n"
                   f"window.VE_AVOPTIONS = {body};\n")
    print(f"{len(data)} encoders, {sum(len(e['options']) for e in data.values())} options -> {out}")


if __name__ == "__main__":
    main()
